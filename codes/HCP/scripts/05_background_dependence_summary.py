#!/usr/bin/env python
# coding: utf-8

"""
Summarize the HCP background-dependence analyses for EC(t) or BEC(t).

Expected input
--------------
The dataframe generated by:

    scripts/04_background_dependence.py

Depending on ``--connectivity-kind``, the script looks for:

    results/HCP_4_df_background_dependence_ECts.pkl
    results/HCP_4_df_background_dependence_BECts.pkl

and falls back to the corresponding CSV file.

Analyses
--------
1. Participant-wise correlation between baseline energy and average
   perturbation magnitude.
2. Participant-wise correlation between baseline energy and average
   evoked energy.
3. Example scatter plots for selected participants.
4. ROI-wise local versus global energy-effect correlations across
   participants.
"""

from pathlib import Path
import argparse

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.stats import pearsonr


# =============================================================================
# Repository paths
# =============================================================================

script_dir = Path(__file__).resolve().parent
hcp_dir = script_dir.parent
repo_dir = hcp_dir.parent.parent
data_dir = hcp_dir / "results" / "dataframes"


# =============================================================================
# Plotting and statistical helpers
# =============================================================================

def nice_axes(ax):
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.grid(ls="--", alpha=0.25)
    return ax


def safe_pearsonr(x, y):
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)

    mask = np.isfinite(x) & np.isfinite(y)
    x = x[mask]
    y = y[mask]

    if len(x) < 3:
        return np.nan, np.nan

    if np.allclose(np.std(x), 0) or np.allclose(np.std(y), 0):
        return np.nan, np.nan

    return pearsonr(x, y)


# =============================================================================
# Load background-dependence dataframe
# =============================================================================

def load_background_dependence_dataframe(df_pkl_path, df_csv_path):
    if df_pkl_path.exists():
        df_bd = pd.read_pickle(df_pkl_path)
        print(f"Loaded dataframe from PKL: {df_pkl_path}")
    elif df_csv_path.exists():
        df_bd = pd.read_csv(df_csv_path)
        print(f"Loaded dataframe from CSV: {df_csv_path}")
    else:
        raise FileNotFoundError(
            "Could not find the selected step-4 PKL or CSV file. "
            f"Tried: {df_pkl_path} and {df_csv_path}. "
            "Run scripts/04_background_dependence.py with the same "
            "--connectivity-kind first."
        )

    expected_cols = [
        "sub_id",
        "roi",
        "time",
        "global_baseline_energy",
        "global_evoked_energy",
        "global_effect_size",
        "global_effect_direction",
        "local_baseline_energy",
        "local_evoked_energy",
        "local_effect_size",
        "local_effect_direction",
    ]

    missing_cols = [
        column
        for column in expected_cols
        if column not in df_bd.columns
    ]

    if missing_cols:
        raise ValueError(
            f"Missing expected columns: {missing_cols}"
        )

    df_bd = df_bd.copy()
    df_bd["sub_id"] = df_bd["sub_id"].astype(str)
    df_bd["roi"] = pd.to_numeric(
        df_bd["roi"],
        errors="coerce",
    ).astype(int)
    df_bd["time"] = pd.to_numeric(
        df_bd["time"],
        errors="coerce",
    ).astype(int)

    print("Dataframe shape:", df_bd.shape)
    print(df_bd.head())

    return df_bd


# =============================================================================
# Participant-wise global analyses
# =============================================================================

def compute_subject_global_table(df_bd):
    return (
        df_bd.groupby(
            ["sub_id", "time"],
            as_index=False,
        )
        .agg(
            global_baseline_energy=(
                "global_baseline_energy",
                "first",
            ),
            global_effect_size_mean=(
                "global_effect_size",
                "mean",
            ),
            global_evoked_energy_mean=(
                "global_evoked_energy",
                "mean",
            ),
        )
    )


def compute_global_effect_correlations(subject_global):
    results_global = []
    scatter_data_global = {}

    for sid, sub_df in subject_global.groupby("sub_id"):
        x = sub_df["global_baseline_energy"].to_numpy()
        y = sub_df["global_effect_size_mean"].to_numpy()

        r, p = safe_pearsonr(x, y)

        results_global.append(
            {
                "sub_id": sid,
                "r": r,
                "p": p,
                "n_timepoints": len(sub_df),
            }
        )
        scatter_data_global[sid] = (x, y)

    df_corr_global = (
        pd.DataFrame(results_global)
        .sort_values("sub_id")
        .reset_index(drop=True)
    )

    print(df_corr_global.head())
    print(
        "Average correlation across subjects:",
        df_corr_global["r"].mean(),
    )

    return df_corr_global, scatter_data_global


def plot_global_effect_histogram(df_corr_global):
    plt.figure(figsize=(6.2, 4.0))
    plt.hist(
        df_corr_global["r"].dropna(),
        bins=15,
        edgecolor="k",
        alpha=0.75,
    )
    plt.axvline(
        df_corr_global["r"].mean(),
        linestyle="--",
        linewidth=2,
        label=f"mean r = {df_corr_global['r'].mean():.2f}",
    )
    plt.xlabel(
        "Pearson r (baseline energy vs average effect size)"
    )
    plt.ylabel("Number of subjects")
    plt.title(
        "Distribution of subject-wise energy-effect correlations"
    )
    plt.legend()
    nice_axes(plt.gca())
    plt.tight_layout()
    plt.show()


def plot_selected_subjects(
    scatter_data_global,
    df_corr_global,
):
    n_plot = min(5, len(scatter_data_global))
    sel_subjects = list(scatter_data_global.keys())[:n_plot]

    fig, axs = plt.subplots(
        1,
        n_plot,
        figsize=(4 * n_plot, 4),
        sharey=True,
    )

    if n_plot == 1:
        axs = [axs]

    for ax, sid in zip(axs, sel_subjects):
        x, y = scatter_data_global[sid]
        row = df_corr_global.loc[
            df_corr_global["sub_id"] == sid
        ].iloc[0]

        ax.scatter(
            x,
            y,
            s=12,
            alpha=0.55,
            edgecolors="none",
        )
        ax.set_title(
            f"{sid}\nr={row['r']:.2f}, p={row['p']:.2g}"
        )
        ax.set_xlabel("Baseline energy")

        if ax == axs[0]:
            ax.set_ylabel("Average effect size")

        if np.all(x > 0):
            ax.set_xscale("log")

        nice_axes(ax)

    plt.tight_layout()
    plt.show()


