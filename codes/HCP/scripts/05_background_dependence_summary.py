# =============================================================================

def compute_node_correlations(df_bd):
    subject_ids = sorted(df_bd["sub_id"].unique())
    roi_ids = np.sort(df_bd["roi"].unique())

    rows = []

    for sid in subject_ids:
        sub_df = df_bd[df_bd["sub_id"] == sid]

        for roi in roi_ids:
            node_df = (
                sub_df[sub_df["roi"] == roi]
                .sort_values("time")
            )

            if node_df.empty:
                continue

            r_local, p_local = safe_pearsonr(
                node_df["local_baseline_energy"].to_numpy(),
                node_df["local_effect_size"].to_numpy(),
            )

            r_global, p_global = safe_pearsonr(
                node_df["global_baseline_energy"].to_numpy(),
                node_df["global_effect_size"].to_numpy(),
            )

            rows.append(
                {
                    "sub_id": sid,
                    "roi": int(roi),
                    "r_local": r_local,
                    "p_local": p_local,
                    "r_global": r_global,
                    "p_global": p_global,
                    "n_timepoints": len(node_df),
                }
            )

    df_node_corr = (
        pd.DataFrame(rows)
        .sort_values(["sub_id", "roi"])
        .reset_index(drop=True)
    )

    print(df_node_corr.head())
    print(
        "Node-wise correlation table shape:",
        df_node_corr.shape,
    )

    return df_node_corr


def summarize_and_plot_node_correlations(df_node_corr):
    local_pivot = (
        df_node_corr.pivot(
            index="sub_id",
            columns="roi",
            values="r_local",
        )
        .sort_index(axis=1)
    )

    global_pivot = (
        df_node_corr.pivot(
            index="sub_id",
            columns="roi",
            values="r_global",
        )
        .sort_index(axis=1)
    )

    mean_r_local = local_pivot.mean(axis=0).to_numpy()
    std_r_local = local_pivot.std(
        axis=0,
        ddof=1,
    ).to_numpy()

    mean_r_global = global_pivot.mean(axis=0).to_numpy()
    std_r_global = global_pivot.std(
        axis=0,
        ddof=1,
    ).to_numpy()

    nodes = local_pivot.columns.to_numpy()

    plt.figure(figsize=(9.0, 4.2))

    plt.plot(
        nodes,
        mean_r_local,
        linewidth=2,
        label="Node-wise local mean r",
    )
    plt.fill_between(
        nodes,
        mean_r_local - std_r_local,
        mean_r_local + std_r_local,
        alpha=0.28,
        label="Node-wise local ±1 SD",
    )

    plt.plot(
        nodes,
        mean_r_global,
        linestyle="--",
        linewidth=2,
        label="Node-wise global mean r",
    )
    plt.fill_between(
        nodes,
        mean_r_global - std_r_global,
        mean_r_global + std_r_global,
        alpha=0.18,
        label="Node-wise global ±1 SD",
    )

    plt.xlabel("Brain region (ROI index)")
    plt.ylabel("Correlation (r)")
    plt.title(
        "Energy-effect correlation: "
        "local vs global baseline energy"
    )
    plt.ylim(-1, 1)
    plt.legend()
    nice_axes(plt.gca())
    plt.tight_layout()
    plt.show()

    summary_local_global = (
        pd.DataFrame(
            {
                "roi": local_pivot.columns.to_numpy(),
                "mean_r_local": mean_r_local,
                "std_r_local": std_r_local,
                "mean_r_global": mean_r_global,
                "std_r_global": std_r_global,
            }
        )
        .sort_values("roi")
        .reset_index(drop=True)
    )

    print(summary_local_global.head())

    return summary_local_global


def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Summarize the HCP background-dependence dataframe "
            "for EC(t) or BEC(t)."
        )
    )
    parser.add_argument(
        "--connectivity-kind",
        choices=["ECts", "BECts"],
        default="ECts",
        help=(
            "Step-4 dataframe to summarize. The original analysis "
            "was applied separately to ECts and BECts."
        ),
    )
    return parser.parse_args()


def main():
    args = parse_args()
    connectivity_kind = args.connectivity_kind

    df_pkl_path = (
        data_dir
        / f"HCP_4_df_background_dependence_{connectivity_kind}.pkl"
    )
    df_csv_path = (
        data_dir
        / f"HCP_4_df_background_dependence_{connectivity_kind}.csv"
    )

    print("Repository directory :", repo_dir)
    print("Results directory    :", data_dir)
    print("Connectivity kind    :", connectivity_kind)
    print("PKL path             :", df_pkl_path)
    print("CSV path             :", df_csv_path)

    df_bd = load_background_dependence_dataframe(
        df_pkl_path,
        df_csv_path,
    )

    subject_global = compute_subject_global_table(df_bd)

    df_corr_global, scatter_data_global = (
        compute_global_effect_correlations(subject_global)
    )

    plot_global_effect_histogram(df_corr_global)
    plot_selected_subjects(
        scatter_data_global,
        df_corr_global,
    )

    compute_poststim_correlations(subject_global)
    plot_example_subject_and_roi(df_bd)

    df_node_corr = compute_node_correlations(df_bd)
    summarize_and_plot_node_correlations(df_node_corr)


if __name__ == "__main__":
    main()
