def plot_example_subject_and_roi(df_bd):
    subject_ids = sorted(df_bd["sub_id"].unique())
    sid = subject_ids[0]
    roi = int(
        df_bd.loc[
            df_bd["sub_id"] == sid,
            "roi",
        ].min()
    )

    df_ex = (
        df_bd[
            (df_bd["sub_id"] == sid)
            & (df_bd["roi"] == roi)
        ]
        .sort_values("time")
    )

    x = df_ex["global_baseline_energy"].to_numpy()
    y_effect = df_ex["global_effect_size"].to_numpy()
    y_evoked = df_ex["global_evoked_energy"].to_numpy()

    r1, p1 = safe_pearsonr(x, y_effect)
    r2, p2 = safe_pearsonr(x, y_evoked)

    fig, (ax1, ax2) = plt.subplots(
        1,
        2,
        figsize=(9.0, 3.8),
    )

    ax1.scatter(
        x,
        y_effect,
        s=18,
        alpha=0.6,
        edgecolors="none",
    )
    ax1.set_xlabel("Baseline energy")
    ax1.set_ylabel("Global effect size")
    ax1.set_title(
        f"{sid}, ROI {roi}\n"
        f"Baseline vs effect size\n"
        f"r={r1:.3f}, p={p1:.2g}"
    )

    if np.all(x > 0):
        ax1.set_xscale("log")

    nice_axes(ax1)

    ax2.scatter(
        x,
        y_evoked,
        s=18,
        alpha=0.6,
        edgecolors="none",
    )
    ax2.set_xlabel("Baseline energy")
    ax2.set_ylabel("Global evoked energy")
    ax2.set_title(
        f"{sid}, ROI {roi}\n"
        f"Baseline vs evoked energy\n"
        f"r={r2:.3f}, p={p2:.2g}"
    )

    if np.all(x > 0):
        ax2.set_xscale("log")

    if np.all(y_evoked > 0):
        ax2.set_yscale("log")

    nice_axes(ax2)

    plt.tight_layout()
    plt.show()


